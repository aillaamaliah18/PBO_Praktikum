    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        int pil = JOptionPane.showConfirmDialog(this,"Apakah ingin mereset semua data?","Konfirmasi Reset",JOptionPane.YES_NO_OPTION);
        if(pil==JOptionPane.YES_NO_OPTION){
            txtHarga.setText("");
            txtJumlah.setText("");
            txtTot.setText("");
            txtDiskon.setText("");
            txtBayar.setText("");
            txtUang.setText("");
            cbKelas.setSelectedIndex(0);
            buttonGroup1.clearSelection();
            JOptionPane.showMessageDialog(this,"Data berhasil direset","Informasi",JOptionPane.INFORMATION_MESSAGE);
            
        }
    }//GEN-LAST:event_btnResetActionPerformed

    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
        try {
        int jumlah = Integer.parseInt(txtJumlah.getText());
        if(jumlah<=0){
            JOptionPane.showMessageDialog(this,"Jumlah tiket harus besar dari 0","Pesan Kesalahan",JOptionPane.ERROR_MESSAGE);
            txtJumlah.setText("");
            txtJumlah.requestFocus();
        }else{
        double harga = Double.parseDouble(txtHarga.getText());
        double total = jumlah * harga;
        double diskon = 0;
        if(jumlah > 5)
            diskon = 0.1 * total;
        double bayar = total - diskon;
        
        txtTot.setText(Double.toString(total));
        txtDiskon.setText(Double.toString(diskon));
        txtBayar.setText(Double.toString(bayar));
      
        }
        }catch(NumberFormatException e){
                JOptionPane.showMessageDialog(this,"Jumlah harus angka bilangan bulat","Pesan Error",JOptionPane.ERROR_MESSAGE);
                txtJumlah.setText("");
                txtJumlah.requestFocus();
                }
    }//GEN-LAST:event_btnHitungActionPerformed

