    private void btnBayarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBayarActionPerformed
        try {
            double bayar = Double.parseDouble(txtBayar.getText());
            double uang = Double.parseDouble(txtUang.getText());
            if(uang<bayar){
                JOptionPane.showMessageDialog(this,"Uang kurang sebesar Rp "+ (bayar-uang),"Pembayaran Gagal",JOptionPane.ERROR_MESSAGE);
            }else if (uang>bayar){
                double kembali = uang-bayar;
                JOptionPane.showMessageDialog(this,"Pembayaran berhasil\nKembalian : Rp " +kembali,"Pembayaran Berhasil",JOptionPane.INFORMATION_MESSAGE);
            }else {
                JOptionPane.showMessageDialog(this,"Pembayaran pas","Pembayaran Berhasil",JOptionPane.INFORMATION_MESSAGE);
            }
        }catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,"Silakan hitung total terlebih dahulu dan masukkan uang","Pesan Error",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBayarActionPerformed

